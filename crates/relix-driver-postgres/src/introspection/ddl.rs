use relix_core::{ColumnInfo, Dialect};

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum Identity {
    None,
    Always,
    ByDefault,
}

impl Identity {
    pub(crate) fn from_code(code: &str) -> Self {
        match code {
            "a" => Self::Always,
            "d" => Self::ByDefault,
            _ => Self::None,
        }
    }
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) struct ColumnDefinition {
    pub(crate) info: ColumnInfo,
    pub(crate) identity: Identity,
    pub(crate) generated: bool,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) struct NamedDefinition {
    pub(crate) name: String,
    pub(crate) definition: String,
}

pub(crate) struct TableDdl<'a> {
    pub(crate) qualified_name: &'a str,
    pub(crate) columns: &'a [ColumnDefinition],
    pub(crate) constraints: &'a [NamedDefinition],
    pub(crate) standalone_indexes: &'a [String],
    pub(crate) partition_key: Option<&'a str>,
    pub(crate) comment: Option<&'a str>,
}

pub(crate) fn create_table(table: &TableDdl<'_>) -> String {
    let mut elements: Vec<String> = table.columns.iter().map(column_clause).collect();
    elements.extend(table.constraints.iter().map(|constraint| {
        format!(
            "CONSTRAINT {} {}",
            quote_identifier(&constraint.name),
            constraint.definition
        )
    }));
    let mut ddl = format!(
        "CREATE TABLE {} (\n    {}\n)",
        table.qualified_name,
        elements.join(",\n    ")
    );
    if let Some(partition_key) = table.partition_key {
        ddl.push_str(&format!(" PARTITION BY {partition_key}"));
    }
    ddl.push_str(";\n");
    for index in table.standalone_indexes {
        ddl.push_str(&format!("\n{index};"));
    }
    if !table.standalone_indexes.is_empty() {
        ddl.push('\n');
    }
    let comments = comment_statements(table);
    if !comments.is_empty() {
        ddl.push('\n');
        ddl.push_str(&comments.join("\n"));
        ddl.push('\n');
    }
    ddl
}

pub(crate) fn create_view(qualified_name: &str, materialized: bool, query: &str) -> String {
    let keyword = if materialized {
        "MATERIALIZED VIEW"
    } else {
        "VIEW"
    };
    format!("CREATE {keyword} {qualified_name} AS\n{}", query.trim_end())
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) struct SequenceOptions {
    pub(crate) data_type: String,
    pub(crate) start: i64,
    pub(crate) increment: i64,
    pub(crate) min_value: i64,
    pub(crate) max_value: i64,
    pub(crate) cache: i64,
    pub(crate) cycle: bool,
}

pub(crate) fn create_sequence(qualified_name: &str, options: &SequenceOptions) -> String {
    format!(
        "CREATE SEQUENCE {qualified_name}\n    AS {}\n    START WITH {}\n    INCREMENT BY {}\n    \
         MINVALUE {}\n    MAXVALUE {}\n    CACHE {}\n    {}CYCLE;",
        options.data_type,
        options.start,
        options.increment,
        options.min_value,
        options.max_value,
        options.cache,
        if options.cycle { "" } else { "NO " }
    )
}

fn column_clause(column: &ColumnDefinition) -> String {
    let info = &column.info;
    let mut clause = format!("{} {}", quote_identifier(&info.name), info.data_type);
    match (
        column.identity,
        column.generated,
        info.default_value.as_deref(),
    ) {
        (Identity::Always, _, _) => clause.push_str(" GENERATED ALWAYS AS IDENTITY"),
        (Identity::ByDefault, _, _) => clause.push_str(" GENERATED BY DEFAULT AS IDENTITY"),
        (Identity::None, true, Some(expression)) => {
            clause.push_str(&format!(" GENERATED ALWAYS AS ({expression}) STORED"));
        }
        (Identity::None, false, Some(default)) => {
            clause.push_str(&format!(" DEFAULT {default}"));
        }
        (Identity::None, _, None) => {}
    }
    if !info.nullable {
        clause.push_str(" NOT NULL");
    }
    clause
}

fn comment_statements(table: &TableDdl<'_>) -> Vec<String> {
    let mut statements = Vec::new();
    if let Some(comment) = table.comment {
        statements.push(format!(
            "COMMENT ON TABLE {} IS {};",
            table.qualified_name,
            Dialect::Postgres.quote_literal(comment)
        ));
    }
    for column in table.columns {
        if let Some(comment) = &column.info.comment {
            statements.push(format!(
                "COMMENT ON COLUMN {}.{} IS {};",
                table.qualified_name,
                quote_identifier(&column.info.name),
                Dialect::Postgres.quote_literal(comment)
            ));
        }
    }
    statements
}

fn quote_identifier(identifier: &str) -> String {
    Dialect::Postgres.quote_identifier(identifier)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn column(name: &str, data_type: &str, nullable: bool, default: Option<&str>) -> ColumnInfo {
        ColumnInfo {
            name: name.into(),
            data_type: data_type.into(),
            nullable,
            default_value: default.map(str::to_owned),
            ordinal: 0,
            is_primary_key: false,
            is_auto_increment: false,
            comment: None,
        }
    }

    #[test]
    fn table_ddl_includes_columns_constraints_indexes_and_comments() {
        let mut commented = column("name", "text", true, Some("'x'::text"));
        commented.comment = Some("display name".into());
        let columns = vec![
            ColumnDefinition {
                info: column("id", "integer", false, None),
                identity: Identity::Always,
                generated: false,
            },
            ColumnDefinition {
                info: commented,
                identity: Identity::None,
                generated: false,
            },
            ColumnDefinition {
                info: column("upper_name", "text", true, Some("upper(name)")),
                identity: Identity::None,
                generated: true,
            },
        ];
        let constraints = vec![NamedDefinition {
            name: "users_pkey".into(),
            definition: "PRIMARY KEY (id)".into(),
        }];
        let indexes = vec!["CREATE INDEX users_name_idx ON public.users USING btree (name)".into()];
        let ddl = create_table(&TableDdl {
            qualified_name: "\"public\".\"users\"",
            columns: &columns,
            constraints: &constraints,
            standalone_indexes: &indexes,
            partition_key: None,
            comment: Some("it's users"),
        });
        assert_eq!(
            ddl,
            "CREATE TABLE \"public\".\"users\" (\n    \
             \"id\" integer GENERATED ALWAYS AS IDENTITY NOT NULL,\n    \
             \"name\" text DEFAULT 'x'::text,\n    \
             \"upper_name\" text GENERATED ALWAYS AS (upper(name)) STORED,\n    \
             CONSTRAINT \"users_pkey\" PRIMARY KEY (id)\n);\n\
             \nCREATE INDEX users_name_idx ON public.users USING btree (name);\n\
             \nCOMMENT ON TABLE \"public\".\"users\" IS 'it''s users';\n\
             COMMENT ON COLUMN \"public\".\"users\".\"name\" IS 'display name';\n"
        );
    }

    #[test]
    fn partitioned_tables_keep_their_partition_key() {
        let columns = vec![ColumnDefinition {
            info: column("day", "date", false, None),
            identity: Identity::None,
            generated: false,
        }];
        let ddl = create_table(&TableDdl {
            qualified_name: "\"public\".\"events\"",
            columns: &columns,
            constraints: &[],
            standalone_indexes: &[],
            partition_key: Some("RANGE (day)"),
            comment: None,
        });
        assert_eq!(
            ddl,
            "CREATE TABLE \"public\".\"events\" (\n    \"day\" date NOT NULL\n) PARTITION BY RANGE (day);\n"
        );
    }

    #[test]
    fn sequence_ddl_lists_all_options() {
        let options = SequenceOptions {
            data_type: "bigint".into(),
            start: 1,
            increment: 2,
            min_value: 1,
            max_value: 100,
            cache: 1,
            cycle: false,
        };
        assert_eq!(
            create_sequence("\"public\".\"s\"", &options),
            "CREATE SEQUENCE \"public\".\"s\"\n    AS bigint\n    START WITH 1\n    INCREMENT BY 2\n    \
             MINVALUE 1\n    MAXVALUE 100\n    CACHE 1\n    NO CYCLE;"
        );
    }

    #[test]
    fn view_ddl_wraps_the_query() {
        assert_eq!(
            create_view("\"public\".\"v\"", true, " SELECT 1;\n"),
            "CREATE MATERIALIZED VIEW \"public\".\"v\" AS\n SELECT 1;"
        );
    }
}
