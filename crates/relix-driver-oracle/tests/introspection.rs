#![allow(clippy::unwrap_used, clippy::expect_used)]

mod common;

use relix_core::{ObjectKind, TableRef};

#[tokio::test]
async fn introspects_catalog_objects_and_definitions() {
    let Some(config) = common::config() else {
        return;
    };
    let connection = common::connect(&config).await;
    let conn = connection.as_ref();
    let sql = common::sql(conn);
    let service = config.settings.database.clone().unwrap();
    let schema = common::schema(&config);
    let parent = common::object_name("parent");
    let child = common::object_name("child");
    let view = common::object_name("child_v");
    let procedure = common::object_name("touch");
    let function = common::object_name("twice");
    let package = common::object_name("pkg");
    let trigger = common::object_name("audit");
    let sequence = common::object_name("seq");
    common::run(
        conn,
        &format!("CREATE TABLE {parent} (id NUMBER(10) CONSTRAINT pk_{parent} PRIMARY KEY)"),
    )
    .await;
    common::run(
        conn,
        &format!(
            "CREATE TABLE {child} (\
               id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_{child} PRIMARY KEY, \
               parent_id NUMBER(10) NOT NULL, \
               code VARCHAR2(20 CHAR) DEFAULT 'x' NOT NULL, \
               amount NUMBER(10, 2), \
               note CLOB, \
               CONSTRAINT uq_{child} UNIQUE (code), \
               CONSTRAINT fk_{child} FOREIGN KEY (parent_id) REFERENCES {parent} (id) ON DELETE CASCADE)"
        ),
    )
    .await;
    common::run(
        conn,
        &format!("CREATE INDEX ix_{child} ON {child} (parent_id, amount)"),
    )
    .await;
    common::run(conn, &format!("COMMENT ON TABLE {parent} IS 'parents'")).await;
    common::run(
        conn,
        &format!("COMMENT ON COLUMN {child}.code IS 'the code'"),
    )
    .await;
    common::run(
        conn,
        &format!("CREATE VIEW {view} AS SELECT id, code FROM {child}"),
    )
    .await;
    common::run(
        conn,
        &format!("CREATE OR REPLACE PROCEDURE {procedure} AS BEGIN NULL; END;\n/"),
    )
    .await;
    common::run(
        conn,
        &format!(
            "CREATE OR REPLACE FUNCTION {function} (v NUMBER) RETURN NUMBER AS BEGIN RETURN v * 2; END;"
        ),
    )
    .await;
    common::run(
        conn,
        &format!(
            "CREATE OR REPLACE PACKAGE {package} AS FUNCTION one RETURN NUMBER; END {package};"
        ),
    )
    .await;
    common::run(
        conn,
        &format!(
            "CREATE OR REPLACE PACKAGE BODY {package} AS FUNCTION one RETURN NUMBER IS BEGIN RETURN 1; END; END {package};"
        ),
    )
    .await;
    common::run(
        conn,
        &format!(
            "CREATE OR REPLACE TRIGGER {trigger} BEFORE INSERT ON {parent} FOR EACH ROW BEGIN NULL; END;"
        ),
    )
    .await;
    common::run(
        conn,
        &format!("CREATE SEQUENCE {sequence} START WITH 5 INCREMENT BY 2"),
    )
    .await;

    let databases = sql.databases().await.unwrap();
    assert_eq!(databases.len(), 1);
    assert!(databases[0].is_default && databases[0].name == service);
    let schemas = sql.schemas(&service).await.unwrap();
    assert!(schemas.contains(&schema), "{schemas:?}");
    assert!(!schemas.iter().any(|name| name == "SYS"));

    let objects = sql.objects(&service, None).await.unwrap();
    let kind_of = |name: &str| {
        objects
            .iter()
            .find(|object| object.object.name == name)
            .map(|object| (object.kind, object.comment.clone()))
    };
    assert_eq!(
        kind_of(&parent),
        Some((ObjectKind::Table, Some("parents".into())))
    );
    assert_eq!(kind_of(&view), Some((ObjectKind::View, None)));
    assert_eq!(kind_of(&procedure), Some((ObjectKind::Procedure, None)));
    assert_eq!(kind_of(&function), Some((ObjectKind::Function, None)));
    assert_eq!(
        kind_of(&package),
        Some((ObjectKind::Procedure, Some("package".into())))
    );
    assert_eq!(kind_of(&trigger), Some((ObjectKind::Trigger, None)));
    assert_eq!(kind_of(&sequence), Some((ObjectKind::Sequence, None)));
    assert!(
        !objects
            .iter()
            .any(|object| object.object.name.starts_with("ISEQ$$"))
    );

    let details = sql
        .table_details(&TableRef::new(None, None, child.clone()))
        .await
        .unwrap();
    assert_eq!(
        details.table,
        TableRef::new(Some(service.clone()), Some(schema.clone()), child.clone())
    );
    assert_eq!(details.kind, ObjectKind::Table);
    assert_eq!(details.primary_key, vec!["ID".to_owned()]);
    let names: Vec<&str> = details.columns.iter().map(|c| c.name.as_str()).collect();
    assert_eq!(names, ["ID", "PARENT_ID", "CODE", "AMOUNT", "NOTE"]);
    let id = &details.columns[0];
    assert!(id.is_primary_key && id.is_auto_increment && !id.nullable);
    assert_eq!(id.data_type, "NUMBER(19)");
    let code = &details.columns[2];
    assert_eq!(code.data_type, "VARCHAR2(20 CHAR)");
    assert_eq!(code.comment.as_deref(), Some("the code"));
    assert_eq!(code.default_value.as_deref(), Some("'x'"));
    assert_eq!(details.columns[3].data_type, "NUMBER(10,2)");
    assert!(details.columns[4].nullable);
    assert!(details.indexes[0].is_primary);
    assert!(
        details
            .indexes
            .iter()
            .any(|index| index.name == format!("UQ_{child}") && index.is_unique)
    );
    let secondary = details
        .indexes
        .iter()
        .find(|index| index.name == format!("IX_{child}"))
        .unwrap();
    assert_eq!(
        secondary.columns,
        vec!["PARENT_ID".to_owned(), "AMOUNT".to_owned()]
    );
    let foreign_key = &details.foreign_keys[0];
    assert_eq!(foreign_key.name, format!("FK_{child}"));
    assert_eq!(foreign_key.columns, vec!["PARENT_ID".to_owned()]);
    assert_eq!(
        foreign_key.referenced_table,
        TableRef::new(Some(service.clone()), Some(schema.clone()), parent.clone())
    );
    assert_eq!(foreign_key.referenced_columns, vec!["ID".to_owned()]);
    let ddl = details.definition.unwrap();
    assert!(ddl.contains("CREATE TABLE"), "{ddl}");
    assert!(ddl.contains("ON DELETE CASCADE"), "{ddl}");

    let view_details = sql
        .table_details(&TableRef::new(None, Some(schema.clone()), view.clone()))
        .await
        .unwrap();
    assert_eq!(view_details.kind, ObjectKind::View);
    assert!(view_details.definition.unwrap().contains("VIEW"));

    let definition_of = |name: &str| {
        let object = objects
            .iter()
            .find(|object| object.object.name == name)
            .unwrap()
            .clone();
        async move { sql.object_definition(&object).await.unwrap().unwrap() }
    };
    assert!(definition_of(&procedure).await.contains("PROCEDURE"));
    assert!(definition_of(&function).await.contains("RETURN v * 2"));
    let package_ddl = definition_of(&package).await;
    assert!(package_ddl.contains("PACKAGE BODY"), "{package_ddl}");
    assert!(definition_of(&trigger).await.contains("BEFORE INSERT"));
    assert!(definition_of(&sequence).await.contains("INCREMENT BY 2"));

    for statement in [
        format!("DROP SEQUENCE {sequence}"),
        format!("DROP PACKAGE {package}"),
        format!("DROP FUNCTION {function}"),
        format!("DROP PROCEDURE {procedure}"),
        format!("DROP VIEW {view}"),
        format!("DROP TABLE {child} PURGE"),
        format!("DROP TABLE {parent} PURGE"),
    ] {
        common::run(conn, &statement).await;
    }
    connection.close().await.unwrap();
}
