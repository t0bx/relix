pub fn spec_for(command: Command) -> Option<&'static CommandSpec> {
    COMMANDS.iter().find(|spec| spec.command == command)
}

pub fn spec_by_id(id: &str) -> Option<&'static CommandSpec> {
    COMMANDS.iter().find(|spec| spec.id == id)
}

#[cfg(test)]
mod tests {
    use super::*;
    use relix_config::KeySequence;
    use std::collections::HashSet;

    #[test]
    fn ids_are_unique_and_keys_parse() {
        let mut ids = HashSet::new();
        for spec in COMMANDS {
            assert!(ids.insert(spec.id), "duplicate id {}", spec.id);
            for key in spec.keys {
                assert!(
                    key.parse::<KeySequence>().is_ok(),
                    "{} has bad key {key}",
                    spec.id
                );
            }
        }
    }

    #[test]
    fn lookup_by_command_and_id() {
        assert_eq!(spec_for(Command::OpenPalette).unwrap().id, "palette.open");
        assert_eq!(
            spec_by_id("query.run").unwrap().command,
            Command::RunStatement
        );
    }
}
