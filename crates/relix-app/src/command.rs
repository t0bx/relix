#[derive(Debug, Clone, Copy)]
pub struct CommandSpec {
    pub command: Command,
    pub id: &'static str,
    pub title: &'static str,
    pub context: KeyContext,
    pub keys: &'static [&'static str],
    pub leader: Option<&'static str>,
    pub in_palette: bool,
}

const fn spec(
    command: Command,
    id: &'static str,
    title: &'static str,
    context: KeyContext,
    keys: &'static [&'static str],
) -> CommandSpec {
    CommandSpec {
        command,
        id,
        title,
        context,
        keys,
        leader: None,
        in_palette: true,
    }
}

const fn led(mut spec: CommandSpec, leader: &'static str) -> CommandSpec {
    spec.leader = Some(leader);
    spec
}

const fn hidden(mut spec: CommandSpec) -> CommandSpec {
    spec.in_palette = false;
    spec
}

